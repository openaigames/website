export function translate(source, locale = 'zh') {
  if (typeof source !== 'string') return source;
  const normalized = source.trim().replace(/\s+/g,' ');
  if(locale!=='en')return chinese[normalized]===undefined?source:source.replace(source.trim(),chinese[normalized]);
  const exact = english[source.trim()] ?? english[normalized] ?? gameEnglish[source.trim()] ?? gameEnglish[normalized];
  if (exact !== undefined) return source.replace(source.trim(), exact);
  const patterns = [
    [/^(\d+) 张可玩卡带$/,(_,n)=>`${n} playable ${n==='1'?'game':'games'}`],
    [/^(\d+) 张已收录卡带$/,(_,n)=>`${n} published ${n==='1'?'game':'games'}`],
    [/^(\d+) 款游戏$/,(_,n)=>`${n} ${n==='1'?'game':'games'}`],
    [/^已收到投稿 #(\d+)「([\s\S]+)」，审核通过后会公开展示。$/,(_,id,title)=>`Received submission #${id} “${title}”. It will be public after review.`],
    [/^已保存投稿 #(\d+)「([\s\S]+)」，大家可以在下方试玩收件箱看到。$/,(_,id,title)=>`Saved submission #${id} “${title}”. It is now in the playtest inbox below.`],
    [/^选择卡带：([\s\S]+)$/,(_,name)=>`Select cartridge: ${translate(name,'en')}`],
    [/^插卡试玩([\s\S]+)$/,(_,name)=>`Insert and play ${translate(name,'en')}`],
    [/^查看([\s\S]+)详情$/,(_,name)=>`View details for ${translate(name,'en')}`],
    [/^查看([\s\S]+)$/,(_,name)=>`View ${translate(name,'en')}`],
    [/^([\s\S]+) 卡带封面$/,(_,name)=>`${translate(name,'en')} cartridge cover`],
    [/^([\s\S]+) (展示画面|试玩截图)$/,(_,name)=>`${translate(name,'en')} gameplay preview`],
    [/^([\s\S]+)试玩$/,(_,name)=>`${translate(name,'en')} playtest`],
    [/^([\s\S]+) · 点一下或拖入卡槽$/,(_,name)=>`${translate(name,'en')} · Click or drag into the slot`],
    [/^([\s\S]+) \/ 社区投稿$/,(_,name)=>`${translate(name,'en')} / Community submission`],
    [/^PR #(\d+) · (投稿预览|已合并|已关闭，未上架)$/,(_,id,status)=>`PR #${id} · ${english[status]}`],
    [/^([\s\S]+) · OpenAIGames$/,(_,name)=>`${translate(name,'en')} · OpenAIGames`]
  ];
  for (const [pattern,replace] of patterns) if (pattern.test(normalized)) return source.replace(source.trim(),normalized.replace(pattern,replace));
  // Server errors sometimes append a UI note; translate only these known sentences.
  if (normalized.endsWith(' 内容仍在表单里。')) return translate(normalized.slice(0,-' 内容仍在表单里。'.length),'en')+' '+english['内容仍在表单里。'];
  return source;
}

export function matchesGame(project,query=''){
  const words=[project.title,project.description,project.category].filter(text=>typeof text==='string');
  return words.flatMap(text=>[text,translate(text,'en')]).join(' ').toLocaleLowerCase().includes(query.trim().toLocaleLowerCase());
}
